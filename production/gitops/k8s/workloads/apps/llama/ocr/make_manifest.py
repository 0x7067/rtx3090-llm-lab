#!/usr/bin/env python3
"""Render ../ocr-manifest.yaml: the runtime manifest the OCR preflight validates.

    python3 make_manifest.py 127.0.0.1:5000/home-llm-ocr@sha256:<digest>

The reviewed example manifest is completed with the built image reference (one
image carries both the layout and vLLM environments), the adapter tree hash, the
lock hashes and the staged model inventory (model-inventory.json). The result is
validated with the service's own preflight before it is written.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "services/ocr/deploy"))
from preflight import sha256_file, source_inventory, validate_manifest  # noqa: E402

image = sys.argv[1]
manifest = json.loads((HERE / "services/ocr/deploy/manifest.example.json").read_text())
inventory = json.loads((HERE / "model-inventory.json").read_text())
deploy = HERE / "services/ocr/deploy"
manifest["artifacts"] = {
    "layoutImage": image,
    "vllmImage": image,
    "adapterTreeSha256": source_inventory()["sha256"],
    "layoutLockSha256": sha256_file(deploy / "requirements.layout.lock"),
    "vllmLockSha256": sha256_file(deploy / "requirements.vllm.lock"),
}
for name in ("ocr", "layout"):
    manifest["models"][name]["files"] = inventory[name]
validate_manifest(manifest, verify_files=False)
body = json.dumps(manifest, indent=2, sort_keys=True)
out = HERE.parent / "ocr-manifest.yaml"
out.write_text(
    "# Generated by ocr/make_manifest.py; do not edit by hand.\n"
    "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: ocr-manifest\n"
    "  annotations:\n    reloader.stakater.com/match: \"true\"\n"
    "data:\n  manifest.json: |\n" + "".join(f"    {line}\n" for line in body.splitlines())
)
print(f"wrote {out}")
